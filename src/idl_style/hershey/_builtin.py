# Default advance widths (left + right) per glyph. Tuned so the visual
# spacing roughly matches Hershey Roman Simplex.
_LEFT_RIGHT: dict[str, tuple[int, int]] = {}
_DEFAULT_HALF = 8


def _bounds(strokes: list[list[tuple[int, int]]], char: str) -> tuple[int, int]:
    if not strokes:
        return (-_DEFAULT_HALF // 2, _DEFAULT_HALF // 2)
    xs = [p[0] for stroke in strokes for p in stroke]
    if not xs:
        return (-_DEFAULT_HALF // 2, _DEFAULT_HALF // 2)
    return (min(xs) - 1, max(xs) + 1)


def builtin_glyphs() -> dict[int, Glyph]:
    """Return the built-in stroke font keyed by ASCII code point."""
    out: dict[int, Glyph] = {}
    for ch, strokes in _STROKES.items():
        left, right = _LEFT_RIGHT.get(ch) or _bounds(strokes, ch)
        polylines = tuple(
            np.asarray(s, dtype=float) if s else np.zeros((0, 2)) for s in strokes
        )
        out[ord(ch)] = Glyph(number=ord(ch), left=left, right=right, strokes=polylines)
    return out
